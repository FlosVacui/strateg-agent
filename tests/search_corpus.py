def build_project(project_id: str = "corpus") -> proj.Project:
    """Создаёт проект с 25 источниками и 60 утверждениями; папка проектов — по `STRATEG_PROJECTS_DIR`."""
    p = proj.create_project(project_id, "автопилот", None)
    with proj.transaction(p):
        for n, (_where, _kind, text) in enumerate(PAGES, start=1):
            path = p.root / snapshot_path(n)
            path.parent.mkdir(exist_ok=True)
            path.write_bytes(text.encode("utf-8"))
        p.sources = build_sources()
        p.claims = build_claims()
        p.save_sources()
        p.save_claims()
        p.save_state()
    return p


def answers(p: proj.Project, fragment: str) -> set[str]:
    """Верные ответы на запрос: источники с фрагментом и утверждения с цитатой, где он есть."""
    found = {f"И-{n}" for n, (_w, _k, text) in enumerate(PAGES, start=1) if fragment in text}
    found |= {c.id for c in p.claims.claims if any(fragment in q.text for q in c.quotes)}
    return found


def queries_with_answers(p: proj.Project) -> list[dict[str, Any]]:
    return [
        {"query": q, "also": also, "fragment": fragment, "note": note, "expect": sorted(answers(p, fragment))}
        for q, also, fragment, note in QUERIES
    ]


def dump_queries(p: proj.Project, path: Path) -> None:
    path.write_text(json.dumps(queries_with_answers(p), ensure_ascii=False, indent=1), encoding="utf-8")
